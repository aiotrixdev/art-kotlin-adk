package com.example.artlibrary.agentic

import kotlinx.coroutines.*

/**
 * Handle for a single logical conversation with the agent (port of Swift `Run`).
 *
 * `done()` resolves on the agent's terminal `agent_general_response`, or throws
 * [AgentErrorException] on `agent_error_response`, or [RunLifecycleException] when
 * the run is force-closed without a terminal event. `sendFeedback(value)` answers
 * the most recent human-input request by sending a `user_reply` carrying the
 * matching `reply_id`. Multi-turn HITL stays inside one Run until a terminal event.
 */
class Run(private val thread: AgentThread) {

    private val lock = Any()

    /**
     * Outbound `ref_id` generated by the SDK when the originating `user_input` was
     * pushed. Empty until the push completes.
     */
    var refId: String = ""
        get() = synchronized(lock) { field }
        private set

    private val result = CompletableDeferred<AgentOutputContent>()
    private var latestHumanInputRef: String? = null
    private var humanInputTimer: Job? = null
    private var closed = false

    private val scope = CoroutineScope(Dispatchers.Default + SupervisorJob())

    /** Whether the run has terminated. */
    fun isClosed(): Boolean = synchronized(lock) { closed }

    /**
     * Resolves on the agent's terminal `agent_general_response`. Throws the typed
     * [AgentErrorException] on `agent_error_response`, or a [RunLifecycleException]
     * when the run is force-closed without a terminal event.
     */
    suspend fun done(): AgentOutputContent = result.await()

    // ── Internal ──────────────────────────────────────────────────────────────

    fun setRefId(value: String) {
        synchronized(lock) { refId = value }
    }

    /** Feeds an inbound event to this run. Invoked by [AgentThread]. */
    fun push(envelope: AgentEventEnvelope) {
        if (isClosed()) return

        when (val payload = envelope.payload) {
            is AgentEventPayload.HumanInput -> {
                val content = payload.content
                // Prefer the inbound message's own ref_id; fall back to its explicit
                // reply_to when ref_id is missing.
                val pendingRef = content.refId.ifEmpty { content.replyTo.ifEmpty { null } }
                synchronized(lock) { latestHumanInputRef = pendingRef }
                clearHumanInputTimer()
                val timeoutSec = content.timeout
                if (timeoutSec != null && timeoutSec > 0) {
                    val timer = scope.launch {
                        delay((timeoutSec * 1000).toLong())
                        val replyTo: String = synchronized(lock) {
                            if (closed) return@launch
                            closed = true
                            latestHumanInputRef ?: ""
                        }
                        val err = AgentError(
                            thread_id = content.threadId,
                            ref_id = "",
                            agent_id = content.agentId,
                            reply_to = replyTo,
                            code = "HUMAN_INPUT_TIMEOUT",
                            message = "No response received within ${timeoutSec}s for human_input_request.",
                            details = mapOf("prompt" to content.prompt, "timeout" to timeoutSec)
                        )
                        result.completeExceptionally(AgentErrorException(err))
                        thread.closeRun(this@Run)
                    }
                    synchronized(lock) { humanInputTimer = timer }
                }
                thread.fireRequestFeedback(content, this)
            }

            is AgentEventPayload.Output -> {
                if (!markClosed()) return
                result.complete(payload.content)
                thread.closeRun(this)
            }

            is AgentEventPayload.Error -> {
                if (!markClosed()) return
                result.completeExceptionally(AgentErrorException(payload.content.toAgentError()))
                thread.closeRun(this)
            }

            else -> {
                // wait / plannerCorrection / threadState / unknown — non-terminal:
                // surfaced to listeners but does not settle.
            }
        }
    }

    /**
     * Sends a reply to the most recent human-input request. Throws
     * [RunLifecycleException] when no input is currently pending. The reply is sent
     * as `user_reply` with `reply_id` set to the originating request's `ref_id`.
     */
    suspend fun sendFeedback(value: Any?) {
        // Consume the pending input *before* sending so a reentrant handler doesn't
        // double-respond.
        val replyId = synchronized(lock) {
            val pending = latestHumanInputRef
            latestHumanInputRef = null
            pending
        } ?: throw RunLifecycleException(
            "Run.sendFeedback: no pending human_input_request to respond to."
        )
        clearHumanInputTimer()
        thread.sendReply(value, replyId)
    }

    /** Force-closes the run. Invoked by [AgentThread] on supersede. */
    fun close(reason: String = "Run closed before terminal event") {
        if (!markClosed()) return
        result.completeExceptionally(RunLifecycleException(reason, superseded = true))
    }

    /** Ends the run: its thread was disposed or its request could not be sent. */
    fun abort(reason: String) {
        if (!markClosed()) return
        result.completeExceptionally(RunLifecycleException(reason))
    }

    /** Marks the run closed and cancels the HITL timer. Returns `false` when it was already closed. */
    private fun markClosed(): Boolean {
        val timer = synchronized(lock) {
            if (closed) return false
            closed = true
            val t = humanInputTimer
            humanInputTimer = null
            t
        }
        timer?.cancel()
        return true
    }

    private fun clearHumanInputTimer() {
        val timer = synchronized(lock) {
            val t = humanInputTimer
            humanInputTimer = null
            t
        }
        timer?.cancel()
    }
}

/**
 * Wraps an [AgentError] as a throwable so it can surface through [Run.done].
 * [agentError] is exposed so callers can branch on `code`.
 */
class AgentErrorException(val agentError: AgentError) :
    Exception("Agent error [${agentError.code}]: ${agentError.message}")

/**
 * Lifecycle errors raised by a [Run] that are NOT agent-emitted (Swift
 * `RunLifecycleError`). Callers typically swallow these. [superseded] is `true`
 * when a newer run on the same thread replaced this one, `false` when the run was
 * closed for another reason (thread disposed, request not sent, no pending input).
 */
class RunLifecycleException(message: String, val superseded: Boolean = false) : Exception(message)
